export type TranslationKey = keyof typeof ja;

export const TRANSLATIONS = { ja, ko } as const;

// 曜日1文字の表示変換（データ値は "月"|"火"|... のまま保持し、表示だけ言語に合わせる）
const DAY_LABELS_KO: Record<string, string> = {
  月: "월", 火: "화", 水: "수", 木: "목", 金: "금", 土: "토", 日: "일",
};

export function dayLabel(language: "ja" | "ko", day: string): string {
  return language === "ko" ? DAY_LABELS_KO[day] ?? day : day;
}

// 相対時刻の表示（各画面に重複していた timeAgo を一元化）
export function timeAgo(language: "ja" | "ko", ms: number): string {
  const L = TRANSLATIONS[language];
  const diff = Date.now() - ms;
  if (diff < 60000) return L["time.justNow"];
  if (diff < 3600000) return `${Math.floor(diff / 60000)}${L["time.minutesAgo"]}`;
  if (diff < 86400000) return `${Math.floor(diff / 3600000)}${L["time.hoursAgo"]}`;
  return `${Math.floor(diff / 86400000)}${L["time.daysAgo"]}`;
}
