// - 判定は src/utils/contentFilter.ts の findBannedWords() が行う。
//   日本語・韓国語は正規化（NFKC・小文字化・空白除去）してから部分一致するので、
//   「し ね」のような簡単な回避は自動的に吸収される。
//   ラテン文字の語だけは空白を残して単語境界で見る（理由は contentFilter.ts）。
// - 短くて一般語に埋もれる語は BANNED_WORD_GUARDS で「この文脈なら侮辱ではない」を併記する。
//   部分一致だけでは上の方針（一般語と当たる語は入れない）を守れないため。
// - ⚠️ これは**種リスト**である。運用しながら通報内容を見て育てること。
