// ------------------------------------------------------------
// 誤検知よけ（2026-11-02 追加）
//
// ブロックに変えた時点で、誤検知は「正当な投稿が止まる」になった。ところが短い語を
// 部分一致で見ていたため、ごく普通の文が弾かれていた。実測した例:
//   「課題が多いしね」「単位も取りやすいしね」… → しね   ※「〜だしね」は接続表現
//   「デブリ（宇宙ごみ）の研究室」「クズ鉄」「ブスッと刺さった」 → デブ / クズ / ブス
//   「시발점에서 출발하는 버스」「시발역」          → 시발   ※始發
//
// pattern は「侮辱ではない出現」を表す。判定時にその部分だけを無効化してから
// 改めて語を探すので、同じ文に本物の侮辱が混じっていれば依然として検知する
// （例:「しねしね」は検知、「多いしね」は検知しない）。
// keep の $1 は前後の文字を残すためのもの。消してしまうと、その文字が別の語の
// 一部だったときに検知が漏れる。
// ------------------------------------------------------------
export const BANNED_WORD_GUARDS: Record<string, { pattern: RegExp; keep: string }> = {
  // ひらがなに続く「しね」は「〜だしね」「〜ないしね」等の接続表現
  しね: { pattern: /([ぁ-ん])しね/gu, keep: "$1 " },
  // カタカナ・長音・漢字が続くなら別の語（デブリ / クズ鉄 / ブスッと）
  デブ: { pattern: /デブ([ァ-ヶー一-龥])/gu, keep: " $1" },
  クズ: { pattern: /クズ([ァ-ヶー一-龥])/gu, keep: " $1" },
  ブス: { pattern: /ブス([ァ-ヶー一-龥])/gu, keep: " $1" },
  // 始發（시발점・시발역・시발지・시발 버스）
  시발: { pattern: /시발([점역지버])/gu, keep: " $1" },
};
